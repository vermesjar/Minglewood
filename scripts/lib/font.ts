/** Draw text at (x, y), each font pixel `s` × `s`, in `rgb`. Returns the width drawn. */
export function text(img: Img, x: number, y: number, str: string, rgb: [number, number, number], s = 2): number {
  let cx = x;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] ?? G['?'];
    for (let r = 0; r < 5; r++)
      for (let c = 0; c < 3; c++) {
        if (g[r * 3 + c] !== '1') continue;
        for (let yy = 0; yy < s; yy++)
          for (let xx = 0; xx < s; xx++) {
            const X = cx + c * s + xx;
            const Y = y + r * s + yy;
            if (X >= 0 && Y >= 0 && X < img.w && Y < img.h) img.d.set([rgb[0], rgb[1], rgb[2], 255], (Y * img.w + X) * 4);
          }
      }
    cx += 4 * s;
  }
  return cx - x;
}

export const textWidth = (str: string, s = 2) => str.length * 4 * s;
